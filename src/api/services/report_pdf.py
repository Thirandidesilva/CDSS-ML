class _NumberedCanvas(pdf_canvas.Canvas):
    """Draws the footer once the page count is known ("Page 1 of 2")."""

    report_id = ""

    def __init__(self, *args, **kwargs) -> None:
        super().__init__(*args, **kwargs)
        self._saved_pages: list[dict] = []

    def showPage(self) -> None:
        self._saved_pages.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        total = len(self._saved_pages)
        for state in self._saved_pages:
            self.__dict__.update(state)
            self._draw_footer(total)
            super().showPage()
        super().save()

    def _draw_footer(self, total: int) -> None:
        y = MARGIN_BOTTOM - 4 * mm
        self.setStrokeColor(colors.HexColor(RULE))
        self.setLineWidth(0.7)
        self.line(MARGIN_X, y + 10, PAGE_WIDTH - MARGIN_X, y + 10)
        self.setFillColor(colors.HexColor(FAINT))
        self.setFont("Helvetica", 7)
