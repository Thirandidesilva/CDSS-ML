def _safe(text) -> str:
    """Latin-1/Windows-1252 only (what Helvetica can draw), then XML-escaped for Paragraph."""
    text = "" if text is None else str(text)
    return escape(text.encode("cp1252", "replace").decode("cp1252"))


def _style(name: str, size: float, *, bold: bool = False, color: str = INK, leading: Optional[float] = None, **kw) -> ParagraphStyle:
    return ParagraphStyle(
        name,
        fontName="Helvetica-Bold" if bold else "Helvetica",
        fontSize=size,
        leading=leading or size * 1.35,
        textColor=colors.HexColor(color),
        **kw,
    )


