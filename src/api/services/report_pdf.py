class PdfRenderer:
    """Turns a report context into PDF bytes. Stateless, so one instance is shared."""

    def render_pdf(self, context: dict) -> bytes:
        report_id = _safe_plain(context["report_display_id"])
        canvas_cls = type("_ReportCanvas", (_NumberedCanvas,), {"report_id": report_id})
        buffer = io.BytesIO()
        try:
            doc = BaseDocTemplate(
                buffer,
                pagesize=A4,
                title=f"Pawsitivity report {report_id}",
                author="Pawsitivity",
            )
            frame = Frame(
                MARGIN_X, MARGIN_BOTTOM, CONTENT_WIDTH, PAGE_HEIGHT - MARGIN_TOP - MARGIN_BOTTOM,
                leftPadding=0, rightPadding=0, topPadding=0, bottomPadding=0,
            )
            doc.addPageTemplates([PageTemplate(id="report", frames=[frame])])
            doc.build([*_page_one(context), *_page_two(context)], canvasmaker=canvas_cls)
        except Exception:
            log.exception("could not render the report PDF")
            raise ApiError(BusinessCode.REPORT_UNAVAILABLE, "the report could not be rendered")
        return buffer.getvalue()

    def close(self) -> None:
        """Nothing to release; kept so callers can treat every renderer alike."""
