class _Logo(Flowable):
    """The blue rounded square with the three white dots from the old HTML template."""

    def __init__(self, size: float = 26) -> None:
        super().__init__()
        self.width = self.height = size

    def draw(self) -> None:
        c, s = self.canv, self.width / 28
        c.setFillColor(colors.HexColor(BLUE))
        c.roundRect(0, 0, 28 * s, 28 * s, 7 * s, stroke=0, fill=1)
        c.setFillColor(colors.white)
        for cx, cy, r in ((10.5, 17, 3.2), (17.5, 17, 3.2), (14, 10, 4)):
            c.circle(cx * s, cy * s, r * s, stroke=0, fill=1)


class _Pill(Flowable):
    """Rounded label; its width follows the text."""

    def __init__(self, text: str, fill: str, ink: str, *, size: float, bold: bool, pad_x: float, pad_y: float) -> None:
        super().__init__()
        self.text, self.fill, self.ink, self.size = text, fill, ink, size
        self.font = "Helvetica-Bold" if bold else "Helvetica"
        self.pad_x = pad_x
        self.width = stringWidth(text, self.font, size) + 2 * pad_x
        self.height = size + 2 * pad_y
        self.hAlign = "LEFT"

    def draw(self) -> None:
        c = self.canv
        c.setFillColor(colors.HexColor(self.fill))
        c.roundRect(0, 0, self.width, self.height, self.height / 2, stroke=0, fill=1)
        c.setFillColor(colors.HexColor(self.ink))
        c.setFont(self.font, self.size)
        c.drawString(self.pad_x, (self.height - self.size) / 2 + self.size * 0.2, self.text)


class _Track(Flowable):
    """A horizontal bar: grey track with a coloured fill covering `fraction` of it."""

    def __init__(self, fraction: float, width: float, height: float, fill: str) -> None:
        super().__init__()
        self.fraction = max(0.0, min(1.0, fraction))
        self.width, self.height, self.fill = width, height, fill

    def draw(self) -> None:
        c, r = self.canv, self.height / 2.5
        c.setFillColor(colors.HexColor(TRACK))
        c.roundRect(0, 0, self.width, self.height, r, stroke=0, fill=1)
        if self.fraction > 0:
            c.setFillColor(colors.HexColor(self.fill))
            c.roundRect(0, 0, max(self.width * self.fraction, 2 * r), self.height, r, stroke=0, fill=1)


class _BarAxis(Flowable):
    """The 0..4 tick labels under the subscale bars."""

    def __init__(self, width: float) -> None:
        super().__init__()
        self.width, self.height = width, 10

    def draw(self) -> None:
        c = self.canv
        c.setFont("Helvetica", 7)
        c.setFillColor(colors.HexColor(FAINT))
        for i in range(5):
            x = self.width * i / 4
            if i == 0:
                c.drawString(x, 1, "0")
            elif i == 4:
                c.drawRightString(x, 1, "4")
            else:
                c.drawCentredString(x, 1, str(i))


class _SeverityChart(Flowable):
    """Severity-over-time chart, drawn from report_chart.layout_severity_chart()."""

    def __init__(self, points, cut_75: float, cut_90: float, width: float = 480, height: float = 200) -> None:
        super().__init__()
        self.layout = layout_severity_chart(points, cut_75, cut_90, width=int(width), height=int(height))
        self.width, self.height = width, height

    def draw(self) -> None:
        c, lay = self.canv, self.layout

        def fy(y: float) -> float:  # chart y grows downwards, PDF y grows upwards
            return self.height - y

        for band in lay.bands:
            c.setFillColor(colors.HexColor(band.fill))
            c.rect(lay.plot_x0, fy(band.y_bottom), lay.plot_x1 - lay.plot_x0, band.y_bottom - band.y_top, stroke=0, fill=1)
            c.setFillColor(colors.HexColor(band.text_color))
            c.setFont("Helvetica", 8)
            c.drawString(lay.plot_x1 + 8, fy((band.y_top + band.y_bottom) / 2) - 3, band.label)

        c.setStrokeColor(colors.HexColor(RULE))
        c.setLineWidth(0.7)
        for y, value in lay.gridlines:
            c.line(lay.plot_x0, fy(y), lay.plot_x1, fy(y))
            c.setFillColor(colors.HexColor(MUTED))
            c.setFont("Helvetica", 8)
            c.drawRightString(lay.plot_x0 - 8, fy(y) - 3, f"{value:g}")

        c.setStrokeColor(colors.HexColor(BLUE))
        if lay.connected:
            c.setLineWidth(1.8)
            path = c.beginPath()
            for i, m in enumerate(lay.markers):
                (path.moveTo if i == 0 else path.lineTo)(m.x, fy(m.y))
            c.drawPath(path, stroke=1, fill=0)

        for m in lay.markers:
            c.setFillColor(colors.white)
            c.setLineWidth(1.8)
            c.circle(m.x, fy(m.y), 3.6, stroke=1, fill=1)
            c.setFillColor(colors.HexColor(INK))
            c.setFont("Helvetica-Bold", 9)
            c.drawCentredString(m.x, fy(m.label_y) - 3, f"{m.theta:.2f}")
            c.setFillColor(colors.HexColor(MUTED))
            c.setFont("Helvetica", 8)
            c.drawCentredString(m.x, fy(lay.plot_y1 + 20) - 3, _safe_plain(m.date_display))


def _safe_plain(text) -> str:
    return ("" if text is None else str(text)).encode("cp1252", "replace").decode("cp1252")


def _box(content, *, fill: str, border: str, radius: float = 6, pad: float = 10, width: float = CONTENT_WIDTH) -> Table:
    table = Table([[content]], colWidths=[width])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(fill)),
        ("BOX", (0, 0), (-1, -1), 0.7, colors.HexColor(border)),
        ("ROUNDEDCORNERS", [radius] * 4),
        ("LEFTPADDING", (0, 0), (-1, -1), pad),
        ("RIGHTPADDING", (0, 0), (-1, -1), pad),
        ("TOPPADDING", (0, 0), (-1, -1), pad),
        ("BOTTOMPADDING", (0, 0), (-1, -1), pad),
    ]))
    return table


def _header(meta_lines: list[str]) -> list:
    brand = Table(
        [[_Logo(), [Paragraph(_BRAND_NAME, _BRAND), Paragraph(_BRAND_TAG, _TAG)]]],
        colWidths=[34, 200],
    )
    brand.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
    ]))
    meta = [Paragraph(line, _META) for line in meta_lines]
    row = Table([[brand, meta]], colWidths=[CONTENT_WIDTH - 240, 240])
    row.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
    ]))
    return [row, HRFlowable(width="100%", thickness=2, color=colors.HexColor(BLUE), spaceBefore=6, spaceAfter=10)]


def _section(title: str, hint: str = "") -> Paragraph:
    extra = f' <font name="Helvetica" color="{FAINT}" size="8">{_safe(hint)}</font>' if hint else ""
    return Paragraph(f"{_safe(title.upper())}{extra}", _SECTION)


